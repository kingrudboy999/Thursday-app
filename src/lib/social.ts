export function formatCount(c?: any) {
  return c >= 1e6
    ? `${(c / 1e6).toFixed(1).replace(".0", "")}m`
    : c >= 1e3
      ? `${(c / 1e3).toFixed(1).replace(".0", "")}k`
      : String(c);
}
